#!/usr/bin/env node

// Deterministic, factual listing optimizer. It deliberately does not call an
// AI provider: the imported catalogue is large and the public copy must be
// traceable to the listing's existing title, taxonomy, media and variation
// data. AI-assisted editing remains available one listing at a time in Admin.
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { createClient } from '@supabase/supabase-js'
import { normalizeTeamSlug } from '../src/lib/league-taxonomy.js'
import { truncateSeoText } from '../src/lib/seo-text.js'

const TARGET_URL = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL || 'https://ofetusgarxcwloxxkhnr.supabase.co'
const SERVICE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.TARGET_SERVICE_KEY || ''
const REPORT_PATH = process.env.SEO_OPTIMIZATION_REPORT || resolve('artifacts', 'seo-optimization-report.json')
const WRITE = process.argv.includes('--write')
const LIMIT = Math.max(0, Number(process.argv.includes('--limit') ? process.argv[process.argv.indexOf('--limit') + 1] : 0) || 0)
const ONLY_ID = process.argv.includes('--id') ? process.argv[process.argv.indexOf('--id') + 1] : ''
const WRITE_CONCURRENCY = Math.max(1, Number(process.env.SEO_WRITE_CONCURRENCY || 12))

const LEAGUE_NAMES = { nfl: 'NFL', mlb: 'MLB', nba: 'NBA', mls: 'MLS' }
const GROUP_NAMES = new Set(['Apparel', 'Hoodies', 'Football Jersey', 'Baseball Jersey', 'Basketball Jersey', 'Soccer Jersey'])
const BAD_PUBLIC_REFERENCE = /fangear(?:sport)?|fgs\s*pro|openai|gpt[-_ ]?image|\bprompt\b|https?:\/\/|www\./i

function clean(value) {
  return String(value ?? '')
    .replace(/https?:\/\/[^\s"'<>]+/gi, ' ')
    .replace(/www\.[^\s"'<>]+/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\b(?:fangear(?:sport)?|fgs\s*pro|openai|gpt[-_ ]?image|\bprompt\b)\b/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function safeText(value, fallback = '') {
  const text = clean(value)
  return BAD_PUBLIC_REFERENCE.test(text) ? fallback : text
}

function slugWords(value) {
  return String(value || '').replace(/[-_]+/g, ' ').replace(/\b\w/g, character => character.toUpperCase()).trim()
}

function teamLabel(slug) {
  const special = {
    'd-c-united': 'D.C. United', 'dc-united': 'D.C. United',
    'la-galaxy': 'LA Galaxy', 'fc-cincinnati': 'FC Cincinnati',
    'fc-dallas': 'FC Dallas', 'cf-montreal': 'CF Montréal',
    'st-louis-city': 'St. Louis CITY', 'new-york-red-bulls': 'New York Red Bulls'
  }
  return special[slug] || slugWords(slug)
}

function leagueLabel(slug) { return LEAGUE_NAMES[String(slug || '').toLowerCase()] || slugWords(slug) }

function trimTo(value, max, min = 0) {
  let text = clean(value)
  if (text.length > max) {
    text = text.slice(0, max + 1).replace(/\s+\S*$/, '').replace(/[,:;\-–—]+$/, '').trim()
  }
  if (text.length < min) return `${text}${text && !/[.!?]$/.test(text) ? '.' : ''}`.trim()
  return text
}

function sentences(value) {
  return clean(value).split(/(?<=[.!?])\s+/).map(item => item.trim()).filter(item => item.length >= 35)
}

function unique(values) { return [...new Set(values.filter(Boolean))] }

// Copy generated by this optimizer must never become the "fact" input on a
// subsequent run.  Otherwise every pass would quote the previous pass and
// gradually grow a duplicated description.  Keep this deliberately narrow so
// genuine merchant-provided copy is preserved.
function isGeneratedCopy(value, title = '') {
  const text = clean(value)
  if (!text) return false
  const escapedTitle = clean(title).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  return new RegExp(`^(?:${escapedTitle}\\s+brings\\b|the listing story stays grounded\\b|design details from the listing\\b|the product page keeps the supplied design title\\b|choose from the listed\\b|review the available variation and price information\\b|when enabled, the custom fields cover\\b|the artwork composition remains designer-led\\b|the page keeps the available product, variation and ordering details together\\b)`, 'i').test(text)
}

function embeddedFact(value) {
  const text = clean(value)
  const markers = ['the listing story stays grounded in the supplied design details:', 'design details from the listing:']
  const lower = text.toLowerCase()
  const marker = markers.find(value => lower.includes(value)) || ''
  const start = marker ? lower.indexOf(marker) : -1
  if (start < 0) return ''
  const rest = text.slice(start + marker.length).trim()
  const end = rest.search(/\s+(?:review the available variation and price information|the artwork composition remains designer-led|when enabled, the custom fields cover)\b/i)
  const fact = clean(end >= 0 ? rest.slice(0, end) : rest)
  return fact.length >= 35 && !BAD_PUBLIC_REFERENCE.test(fact) ? fact : ''
}

function canonicalTaxonomy(product) {
  const source = product.taxonomy && typeof product.taxonomy === 'object' ? product.taxonomy : {}
  const league = String(source.league || product.league || '').toLowerCase().trim()
  const team = normalizeTeamSlug(league, source.team || product.team || '')
  const group = GROUP_NAMES.has(product.product_group) ? product.product_group : (product.product_group || 'Apparel')
  return {
    ...source,
    ...(league ? { league } : {}),
    ...(team ? { team } : {}),
    ...(source.sport || league ? { sport: String(source.sport || ({ nfl: 'football', mlb: 'baseball', nba: 'basketball', mls: 'soccer' }[league] || '')).toLowerCase() } : {}),
    productGroup: group
  }
}

function primaryMedia(product) {
  const media = Array.isArray(product.media) ? product.media : []
  if (media.length) return media
  if (!product.image) return []
  return [{ id: `media-${product.id}`, type: 'IMAGE', url: product.image, alt: `${product.title || 'Product'} product image`, createdAt: null }]
}

function extractFacts(product) {
  const blocks = Array.isArray(product.content_blocks) ? product.content_blocks : []
  const blockFacts = blocks.map(block => block?.content).flatMap(sentences)
  const descFacts = sentences(product.description)
  const subtitleFacts = sentences(product.subtitle)
  return unique([...blockFacts, ...descFacts, ...subtitleFacts, ...descFacts.map(embeddedFact), ...blockFacts.map(embeddedFact)])
    .filter(item => !BAD_PUBLIC_REFERENCE.test(item) && !isGeneratedCopy(item, product.title))
    .slice(0, 3)
}

function makeDescription(product, taxonomy, facts) {
  const title = safeText(product.title, 'Extra Time listing')
  const team = teamLabel(taxonomy.team)
  const league = leagueLabel(taxonomy.league)
  const group = String(taxonomy.productGroup || product.product_group || 'apparel').toLowerCase()
  const anchor = team && team !== 'Untitled' ? `${team} ${league || ''}`.trim() : (league || 'match-day')
  const rawFallback = [product.subtitle, product.description]
    .flatMap(value => sentences(value))
    .find(value => !isGeneratedCopy(value, product.title) && !BAD_PUBLIC_REFERENCE.test(value))
  const fact = facts[0] || safeText(rawFallback, '')
  const optionNames = Array.isArray(product.pod_product_options)
    ? product.pod_product_options.map(option => option.name).filter(Boolean)
    : []
  const customLabels = Array.isArray(product.custom_fields) ? product.custom_fields.map(field => field.label).filter(Boolean) : []
  const lines = [
    `${title} brings ${anchor} character to a designer-led ${group} piece for supporters who want a considered game-day layer.`,
    fact ? `Design details from the listing: ${fact}` : `The product page keeps the supplied design title and catalogue classification at the centre of the story.`,
    optionNames.length ? `Choose from the listed ${optionNames.join(' and ').toLowerCase()} variations shown on this page.` : 'Review the available variation and price information before adding it to your order.',
    customLabels.length ? `When enabled, the custom fields cover ${customLabels.join(', ').toLowerCase()} so the personal layer stays within the fixed artwork system.` : 'The artwork composition remains designer-led while the product information stays clear and easy to compare.'
  ]
  return trimTo(lines.join(' '), 900, 220)
}

function makeSeoTitle(product, taxonomy) {
  const team = teamLabel(taxonomy.team)
  const league = leagueLabel(taxonomy.league)
  const group = String(taxonomy.productGroup || product.product_group || 'Fan apparel')
  const title = safeText(product.title, 'Extra Time listing')
  const lead = team ? `${team} ${group}` : league ? `${league} ${group}` : `${group} — ${title}`
  return trimTo(`${lead} | Extra Time`, 60, 30)
}

function makeSeoDescription(description, product, taxonomy) {
  const prefix = taxonomy.team ? `${teamLabel(taxonomy.team)} ${leagueLabel(taxonomy.league)} fanwear.` : `${leagueLabel(taxonomy.league) || 'Extra Time'} fanwear.`
  return truncateSeoText(`${prefix} ${description}`, 160, 110)
}

function makeBlocks(product, description, facts) {
  const existing = Array.isArray(product.content_blocks)
    ? product.content_blocks.filter(block => clean(block?.content) && !isGeneratedCopy(block.content, product.title))
    : []
  const total = existing.reduce((sum, block) => sum + clean(block.content).length, 0)
  if (existing.length >= 2 && total >= 250) return existing
  const detail = facts.length ? facts.join(' ') : 'The page keeps the available product, variation and ordering details together for a faster decision.'
  return [
    { id: `block-story-${product.id}`, type: 'heading', content: 'The story', mediaId: '' },
    { id: `block-copy-${product.id}`, type: 'paragraph', content: description, mediaId: '' },
    { id: `block-details-${product.id}`, type: 'heading', content: 'Details', mediaId: '' },
    { id: `block-detail-copy-${product.id}`, type: 'paragraph', content: detail, mediaId: '' }
  ]
}

function buildTags(product, taxonomy) {
  const existing = Array.isArray(product.tags) ? product.tags : []
  const tags = existing.map(value => clean(value).toLowerCase().replace(/\s+/g, '-'))
  if (taxonomy.league) tags.push(taxonomy.league)
  if (taxonomy.team) tags.push(taxonomy.team)
  if (taxonomy.productGroup) tags.push(taxonomy.productGroup.toLowerCase().replace(/\s+/g, '-'))
  if (Array.isArray(product.custom_fields) && product.custom_fields.length) tags.push('customizable')
  return unique(tags.filter(tag => tag && !BAD_PUBLIC_REFERENCE.test(tag))).slice(0, 30)
}

function variantStats(product, variantsByProduct) {
  const variants = variantsByProduct.get(product.id) || []
  const active = variants.filter(row => row.status === 'ACTIVE')
  return {
    variants,
    active,
    hasActive: active.length > 0,
    hasStock: active.some(row => Number(row.inventory) > 0),
    hasPrice: active.some(row => Number(row.price) > 0)
  }
}

function scoreAndReasons(product, next, stats) {
  const reasons = []
  if (!next.image) reasons.push('MISSING_PRIMARY_IMAGE')
  if (next.description.length < 160) reasons.push('DESCRIPTION_TOO_SHORT')
  if (next.description.length > 950) reasons.push('DESCRIPTION_TOO_LONG')
  if (next.seo.title.length < 30 || next.seo.title.length > 65) reasons.push('SEO_TITLE_LENGTH')
  if (next.seo.description.length < 120 || next.seo.description.length > 180) reasons.push('SEO_DESCRIPTION_LENGTH')
  if (next.media.length < 1) reasons.push('MISSING_MEDIA')
  if (next.contentBlocks.length < 2 || next.contentBlocks.reduce((sum, row) => sum + clean(row.content).length, 0) < 250) reasons.push('CONTENT_TOO_THIN')
  if (!stats.hasActive) reasons.push('NO_ACTIVE_VARIANT')
  if (!stats.hasPrice) reasons.push('NO_PRICED_VARIANT')
  if (!stats.hasStock) reasons.push('NO_STOCKED_VARIANT')
  if (!next.taxonomy.league && !next.taxonomy.team) reasons.push('TAXONOMY_REVIEW_REQUIRED')
  const score = Math.max(0, Math.min(100,
    (next.image ? 15 : 0) + (next.media.length >= 2 ? 10 : next.media.length ? 6 : 0) +
    (next.description.length >= 220 ? 20 : next.description.length >= 160 ? 14 : 0) +
    (next.seo.title.length >= 30 && next.seo.title.length <= 60 ? 15 : 0) +
    (next.seo.description.length >= 145 && next.seo.description.length <= 175 ? 15 : 0) +
    (next.contentBlocks.length >= 4 ? 10 : next.contentBlocks.length >= 2 ? 6 : 0) +
    (stats.hasActive ? 5 : 0) + (stats.hasPrice ? 5 : 0) + (stats.hasStock ? 5 : 0)
  ))
  const technicalReady = reasons.every(reason => !['MISSING_PRIMARY_IMAGE', 'DESCRIPTION_TOO_SHORT', 'SEO_TITLE_LENGTH', 'SEO_DESCRIPTION_LENGTH', 'MISSING_MEDIA', 'CONTENT_TOO_THIN', 'NO_ACTIVE_VARIANT', 'NO_PRICED_VARIANT', 'NO_STOCKED_VARIANT'].includes(reason))
  const seoStatus = technicalReady ? (product.status === 'PUBLISHED' ? 'INDEXABLE' : 'READY') : 'BLOCKED'
  return { score, reasons, seoStatus }
}

async function allRows(client, table, select, pageSize = 1000) {
  const rows = []
  for (let offset = 0; ; offset += pageSize) {
    const { data, error } = await client.from(table).select(select).range(offset, offset + pageSize - 1)
    if (error) throw error
    rows.push(...(data || []))
    if (!data || data.length < pageSize) return rows
  }
}

function duplicateGroups(rows, field) {
  const groups = new Map()
  for (const row of rows) {
    const value = clean(field === 'description' ? row.description : row.seo?.description).toLowerCase()
    if (!value) continue
    const list = groups.get(value) || []
    list.push(row.id)
    groups.set(value, list)
  }
  return [...groups.values()].filter(group => group.length > 1).sort((a, b) => b.length - a.length)
}

async function main() {
  if (WRITE && !/^sb_secret_|^eyJ/.test(SERVICE_KEY)) throw new Error('Write mode requires SUPABASE_SERVICE_ROLE_KEY (server-only).')
  const client = createClient(TARGET_URL, SERVICE_KEY || process.env.VITE_SUPABASE_ANON_KEY || '', { auth: { persistSession: false, autoRefreshToken: false } })
  const products = await allRows(client, 'pod_products', 'id,status,title,subtitle,description,seo,seo_status,seo_quality_score,seo_block_reasons,image,media,content_blocks,tags,product_group,taxonomy,custom_fields,inventory,updated_at')
  let importedRows = []
  try {
    importedRows = await allRows(client, 'pod_catalog_imports', 'entity_id,entity_type')
  } catch (error) {
    // The import ledger is intentionally private. A read-only dry run with an
    // anon key should still be useful; service-role/write runs keep the full
    // imported-vs-native report.
    if (WRITE || !['42501', 'PGRST116'].includes(String(error?.code || ''))) throw error
    console.warn('[seo] Import ledger is private; continuing without imported flags.')
  }
  const imported = new Set(importedRows.filter(row => row.entity_type === 'PRODUCT').map(row => row.entity_id))
  const variants = await allRows(client, 'pod_product_variants', 'id,product_id,status,price,inventory,sku')
  const variantsByProduct = new Map()
  for (const variant of variants) {
    const list = variantsByProduct.get(variant.product_id) || []
    list.push(variant)
    variantsByProduct.set(variant.product_id, list)
  }
  let scope = products
  if (ONLY_ID) scope = scope.filter(product => product.id === ONLY_ID)
  if (LIMIT) scope = scope.slice(0, LIMIT)
  const beforeDescriptionDuplicates = duplicateGroups(scope, 'description')
  const beforeSeoDuplicates = duplicateGroups(scope, 'seo')
  const changes = []
  const nextRows = []
  for (const product of scope) {
    const taxonomy = canonicalTaxonomy(product)
    const facts = extractFacts(product)
    const description = makeDescription(product, taxonomy, facts)
    const seo = {
      ...(product.seo && typeof product.seo === 'object' ? product.seo : {}),
      title: makeSeoTitle(product, taxonomy),
      description: makeSeoDescription(description, product, taxonomy)
    }
    const media = primaryMedia(product)
    const contentBlocks = makeBlocks(product, description, facts)
    const next = { ...product, description, seo, media, contentBlocks, tags: buildTags(product, taxonomy), taxonomy, image: product.image || media[0]?.url || '' }
    const stats = variantStats(product, variantsByProduct)
    const gate = scoreAndReasons(product, next, stats)
    const row = {
      ...next,
      seoStatus: gate.seoStatus,
      seoQualityScore: gate.score,
      seoBlockReasons: gate.reasons,
      seoReviewedAt: new Date().toISOString()
    }
    if (gate.seoStatus === 'INDEXABLE') row.seoPublishedAt = product.seo_published_at || new Date().toISOString()
    else row.seoPublishedAt = null
    nextRows.push(row)
    const changed = ['description', 'seo', 'media', 'contentBlocks', 'tags', 'taxonomy', 'image', 'seoStatus', 'seoQualityScore', 'seoBlockReasons'].some(key => JSON.stringify(product[key === 'contentBlocks' ? 'content_blocks' : key === 'seoStatus' ? 'seo_status' : key === 'seoQualityScore' ? 'seo_quality_score' : key === 'seoBlockReasons' ? 'seo_block_reasons' : key]) !== JSON.stringify(row[key]))
    if (changed) changes.push({ id: product.id, title: product.title, imported: imported.has(product.id), beforeStatus: product.status, seoStatus: row.seoStatus, score: row.seoQualityScore, reasons: row.seoBlockReasons })
  }
  if (WRITE) {
    let completed = 0
    for (let offset = 0; offset < nextRows.length; offset += WRITE_CONCURRENCY) {
      const batch = nextRows.slice(offset, offset + WRITE_CONCURRENCY)
      await Promise.all(batch.map(async row => {
        const { error } = await client.from('pod_products').update({
        description: row.description,
        seo: { ...row.seo, status: row.seoStatus, quality_score: row.seoQualityScore, block_reasons: row.seoBlockReasons },
        media: row.media,
        content_blocks: row.contentBlocks,
        tags: row.tags,
        product_group: row.productGroup || row.taxonomy.productGroup || '',
        taxonomy: row.taxonomy,
        image: row.image || null,
        seo_status: row.seoStatus,
        seo_quality_score: row.seoQualityScore,
        seo_block_reasons: row.seoBlockReasons,
        seo_reviewed_at: row.seoReviewedAt,
        seo_published_at: row.seoPublishedAt
        }).eq('id', row.id)
        if (error) throw new Error(`${row.id}: ${error.message}`)
        completed += 1
      }))
      if (completed % 100 < WRITE_CONCURRENCY || completed === nextRows.length) console.log(`Optimized ${completed}/${nextRows.length}`)
    }
  }
  const afterDescriptionDuplicates = duplicateGroups(nextRows, 'description')
  const afterSeoDuplicates = duplicateGroups(nextRows, 'seo')
  const report = {
    generatedAt: new Date().toISOString(), mode: WRITE ? 'WRITE' : 'DRY_RUN', targetProject: new URL(TARGET_URL).hostname.split('.')[0],
    scope: scope.length, importedInScope: scope.filter(row => imported.has(row.id)).length,
    changed: changes.length, indexable: nextRows.filter(row => row.seoStatus === 'INDEXABLE').length,
    ready: nextRows.filter(row => row.seoStatus === 'READY').length, blocked: nextRows.filter(row => row.seoStatus === 'BLOCKED').length,
    duplicateDescriptionsBefore: beforeDescriptionDuplicates.length, duplicateDescriptionsAfter: afterDescriptionDuplicates.length,
    duplicateSeoDescriptionsBefore: beforeSeoDuplicates.length, duplicateSeoDescriptionsAfter: afterSeoDuplicates.length,
    thinBefore: scope.filter(row => clean(row.description).length < 160 || (row.content_blocks || []).length < 2 || (row.media || []).length < 1).length,
    samples: changes.slice(0, 40),
    blockedReasons: Object.fromEntries([...new Set(nextRows.flatMap(row => row.seoBlockReasons))].map(reason => [reason, nextRows.filter(row => row.seoBlockReasons.includes(reason)).length]))
  }
  await mkdir(resolve(REPORT_PATH, '..'), { recursive: true })
  await writeFile(REPORT_PATH, JSON.stringify(report, null, 2), 'utf8')
  console.log(JSON.stringify({ ...report, report: REPORT_PATH }, null, 2))
}

main().catch(error => {
  const detail = error instanceof Error ? error.message : (error?.message || JSON.stringify(error))
  console.error(`SEO optimizer failed: ${detail}`)
  process.exitCode = 1
})
